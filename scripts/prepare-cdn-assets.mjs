import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, extname } from "node:path";
import { meixihuReferences, polyReferences } from "../src/references.js";

const files = [
  ...new Set([...meixihuReferences, ...polyReferences].map(ref => `reference/${ref.file}`)),
  "models/stage-actors.bin",
  "models/LICENSE.txt",
];
const assets = {};
const config = JSON.parse(await readFile("config/cdn.json", "utf8"));
const check = process.argv.includes("--check");
for (const file of files) {
  const bytes = await readFile(`public/${file}`);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const ext = extname(file);
  const path = `${file.slice(0, -ext.length)}.${sha256.slice(0, 16)}${ext}`;
  assets[file] = { path, bytes: bytes.length, sha256 };
  if (!check) {
    await mkdir(dirname(`.cdn-assets/${path}`), { recursive: true });
    await writeFile(`.cdn-assets/${path}`, bytes);
  }
}
const source = `// Generated by scripts/prepare-cdn-assets.mjs. Do not edit by hand.\nexport const CDN_CONFIG = ${JSON.stringify(config, null, 2)};\nexport const CDN_ASSETS = ${JSON.stringify(assets, null, 2)};\n`;
if (check) {
  if (await readFile("src/asset-manifest.js", "utf8") !== source) {
    throw new Error("CDN assets changed. Run npm run assets:prepare and publish before release.");
  }
} else {
  await writeFile("src/asset-manifest.js", source);
  await writeFile(".cdn-assets/manifest.json", JSON.stringify({ config, assets }, null, 2) + "\n");
}
console.log("[THEATRE_ASSETS]", JSON.stringify({ event: check ? "verified" : "prepared", files: files.length }));
